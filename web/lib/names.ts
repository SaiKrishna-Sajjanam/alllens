/** Name of a state/UT or topic in an extra interface language, or undefined (caller falls back). */
export function extraName(kind: 'state' | 'topic', id: string, lang: Lang): string | undefined {
  if (lang === 'en' || lang === 'te') return undefined;
  const ids: readonly string[] = kind === 'state' ? STATE_IDS : TOPIC_IDS;
  const i = ids.indexOf(id);
  return i < 0 ? undefined : (kind === 'state' ? STATES : TOPICS)[lang][i];
}
